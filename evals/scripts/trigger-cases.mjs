#!/usr/bin/env node
// Generates trigger eval cases for a skill from evals/<skill>/queries.json.
// Usage: node evals/scripts/trigger-cases.mjs <skill>
//
// Each query becomes evals/<skill>/cases/<arm>/<name>/{case.yaml,stage.sh}.
// Arm "plain" runs against the bare fixture repo; arm "pointer" (only when the
// query file names a pointer) appends that file to the fixture's CLAUDE.md.

import {
  chmodSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const evalsDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const skill = process.argv[2];
if (!skill) {
  console.error("Usage: node evals/scripts/trigger-cases.mjs <skill>");
  process.exit(1);
}

const config = JSON.parse(
  readFileSync(join(evalsDir, skill, "queries.json"), "utf8"),
);
const arms = config.pointer ? ["plain", "pointer"] : ["plain"];

// A change is an Edit, Write or NotebookEdit call, or a Bash command that
// commits, opens a pull request or deletes files. Quotes inside tool results
// are JSON-escaped in the trace, so these patterns only match real tool calls.
const change = String.raw`"name":"(?:Edit|Write|NotebookEdit)"|"name":"Bash","input":\{"command":"[^"]*?\b(?:git commit|gh pr create|rm|trash|git rm)\b`;
const loadedBeforeChange = String.raw`^(?:(?!${change}).)*"name":"Skill","input":\{"skill":"[^"]*\b${config.skill}"`;

const graders = {
  shouldTrigger: `  - type: regex
    name: loaded-before-first-change
    target: trace
    flags: s
    pattern: '${loadedBeforeChange.replaceAll("'", "''")}'`,
  nearMiss: `  - type: tool_used
    name: not-loaded
    tool: Skill
    input_match: '\\b${config.skill}\\b'
    min: 0
    max: 0`,
};

for (const arm of arms) {
  const armDir = join(evalsDir, skill, "cases", arm);
  const names = new Set(config.queries.map((query) => query.name));
  if (existsSync(armDir)) {
    for (const stale of readdirSync(armDir).filter(
      (name) => !names.has(name),
    )) {
      console.warn(`stale case not in queries.json: ${join(armDir, stale)}`);
    }
  }

  for (const { name, query, should_trigger: shouldTrigger } of config.queries) {
    const caseDir = join(armDir, name);
    mkdirSync(caseDir, { recursive: true });

    const pointer =
      arm === "pointer" ? ` "$here/../../../${config.pointer}"` : "";
    writeFileSync(
      join(caseDir, "stage.sh"),
      `#!/bin/bash
# Generated by evals/scripts/trigger-cases.mjs. Do not edit.
here="$(dirname "$0")"
exec "$here/../../../../fixtures/stage.sh" ${config.fixture}${pointer}
`,
    );
    chmodSync(join(caseDir, "stage.sh"), 0o755);

    writeFileSync(
      join(caseDir, "case.yaml"),
      `# Generated by evals/scripts/trigger-cases.mjs from ${skill}/queries.json. Do not edit.
schema_version: "1.0"
name: ${skill}/${arm}/${name}
tags: [${skill}, ${arm}, ${shouldTrigger ? "should-trigger" : "near-miss"}]
context:
  scaffold_script: stage.sh
execution:
  prompt: ${JSON.stringify(query)}
  max_turns: 15
  allowed_tools: [Read, Glob, Grep, Edit, Write, Bash, Skill]
runs: 3
graders:
${shouldTrigger ? graders.shouldTrigger : graders.nearMiss}
`,
    );
  }
}

console.log(
  `Wrote ${config.queries.length * arms.length} cases for ${skill} (${arms.join(", ")})`,
);
