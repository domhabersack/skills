#!/usr/bin/env node
// Generates trigger eval cases for a skill from evals/<skill>/queries.json.
// Usage: node evals/scripts/trigger-cases.mjs <skill>
//
// Each query becomes evals/<skill>/cases/<arm>/<name>/{case.yaml,stage.sh}.
// Arm "plain" runs against the bare fixture repo; arm "pointer" (only when the
// query file names a pointer) appends that file to the fixture's CLAUDE.md.

import {
  chmodSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const evalsDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const skill = process.argv[2];
if (!skill) {
  console.error("Usage: node evals/scripts/trigger-cases.mjs <skill>");
  process.exit(1);
}

const config = JSON.parse(
  readFileSync(join(evalsDir, skill, "queries.json"), "utf8"),
);
const arms = config.pointer ? ["plain", "pointer"] : ["plain"];

// A change is an Edit, Write, MultiEdit or NotebookEdit call, or a Bash command
// that changes files, history or a pull request. In the trace, the command is a
// JSON string, so quotes inside it are escaped (\") and `str` steps over them
// instead of stopping. Commands match only at the start of the command or after
// a separator, so `--rm` or `npm run trash-cache` don't count as changes.
// Redirects count wherever they appear, except to /dev/null or another stream.
// When in doubt this overcounts changes, which makes should-trigger cases
// stricter rather than letting a late load pass.
const str = String.raw`(?:[^"\\]|\\.)*?`;
const start = String.raw`(?:${str}(?:[;&|(]|\\n))?\s*(?:sudo\s+)?`;
const commands = [
  String.raw`git\s+(?:commit|push|rm|mv|apply|restore)\b`,
  String.raw`gh\s+pr\s+(?:create|edit|merge)\b`,
  String.raw`(?:rm|trash|mv|cp|touch|mkdir|rmdir|tee|patch)\b`,
  String.raw`(?:sed|perl)\b(?:[^"\\;&|]|\\.)*?\s(?:-[A-Za-z]*i|--in-place)`,
  String.raw`(?:npm|pnpm|yarn|bun)\s+(?:add|remove|rm|uninstall|un|upgrade|update|up)\b`,
  String.raw`(?:npm|pnpm|yarn|bun)\s+(?:install|i)(?:\s+-\S+)*\s+[^-\s"\\;&|]`,
];
const redirect = String.raw`${str}(?<![0-9&=>-])>>?\s*(?!&|/dev/null)[^\s"\\;&|]`;
const change = String.raw`"name":"(?:Edit|Write|MultiEdit|NotebookEdit)"|"name":"Bash","input":\{"command":"(?:${start}(?:${commands.join("|")})|${redirect})`;
const loadedBeforeChange = String.raw`^(?:(?!${change}).)*"name":"Skill","input":\{"skill":"[^"]*\b${config.skill}"`;

const graders = {
  shouldTrigger: `  - type: regex
    name: loaded-before-first-change
    target: trace
    flags: s
    pattern: '${loadedBeforeChange.replaceAll("'", "''")}'`,
  nearMiss: `  - type: tool_used
    name: not-loaded
    tool: Skill
    input_match: '\\b${config.skill}\\b'
    min: 0
    max: 0`,
};

for (const arm of arms) {
  const armDir = join(evalsDir, skill, "cases", arm);
  const names = new Set(config.queries.map((query) => query.name));
  if (existsSync(armDir)) {
    for (const stale of readdirSync(armDir).filter(
      (name) => !names.has(name),
    )) {
      removeGenerated(join(armDir, stale));
    }
  }

  for (const {
    name,
    query,
    should_trigger: shouldTrigger,
    staged,
  } of config.queries) {
    const caseDir = join(armDir, name);
    mkdirSync(caseDir, { recursive: true });

    const flags = staged ? " --staged" : "";
    const pointer =
      arm === "pointer" ? ` "$here/../../../${config.pointer}"` : "";
    writeFileSync(
      join(caseDir, "stage.sh"),
      `#!/bin/bash
# Generated by evals/scripts/trigger-cases.mjs. Do not edit.
here="$(dirname "$0")"
exec "$here/../../../../fixtures/stage.sh"${flags} ${config.fixture}${pointer}
`,
    );
    chmodSync(join(caseDir, "stage.sh"), 0o755);

    writeFileSync(
      join(caseDir, "case.yaml"),
      `# Generated by evals/scripts/trigger-cases.mjs from ${skill}/queries.json. Do not edit.
schema_version: "1.0"
name: ${skill}/${arm}/${name}
tags: [${skill}, ${arm}, ${shouldTrigger ? "should-trigger" : "near-miss"}]
context:
  scaffold_script: stage.sh
execution:
  prompt: ${JSON.stringify(query)}
  max_turns: 15
  allowed_tools: [Read, Glob, Grep, Edit, Write, Bash, Skill]
runs: 3
graders:
${shouldTrigger ? graders.shouldTrigger : graders.nearMiss}
`,
    );
  }
}

// Arms that queries.json no longer asks for, such as "pointer" after the
// pointer is removed, would otherwise keep running and counting.
const casesDir = join(evalsDir, skill, "cases");
for (const arm of readdirSync(casesDir).filter((arm) => !arms.includes(arm))) {
  removeGenerated(join(casesDir, arm));
}

console.log(
  `Wrote ${config.queries.length * arms.length} cases for ${skill} (${arms.join(", ")})`,
);

// Removes a case or arm directory left over from an earlier queries.json, but
// only when everything in it was generated by this script.
function removeGenerated(dir) {
  const generated = (caseDir) =>
    existsSync(join(caseDir, "case.yaml")) &&
    readFileSync(join(caseDir, "case.yaml"), "utf8").startsWith(
      "# Generated by evals/scripts/trigger-cases.mjs",
    );
  const caseDirs = existsSync(join(dir, "case.yaml"))
    ? [dir]
    : readdirSync(dir).map((name) => join(dir, name));
  if (!caseDirs.every(generated)) {
    console.error(`not removing ${dir}: it holds files this script didn't generate`);
    process.exitCode = 1;
    return;
  }
  rmSync(dir, { recursive: true });
  console.log(`removed stale ${dir}`);
}
